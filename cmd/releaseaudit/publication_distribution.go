package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"
)

const publicationChecksumsName = "SHA256SUMS"

// The complete supply-chain bundle is verified by the caller before projection.
// This function rechecks the original manifest and archive hashes; the generated
// checksum asset is virtual, so the immutable evidence inventory never changes.
func publicationAssets(dir string) ([]publicationAsset, error) {
	root, err := supplyOpen(dir)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	data, err := supplyRead(root, "candidate/candidate-manifest.json")
	if err != nil {
		return nil, err
	}
	var manifest candidateManifest
	if err := strictCandidateBytes(data, &manifest); err != nil {
		return nil, err
	}
	if manifest.Schema != candidateSchema || validateCandidateIdentity(manifest.Version, manifest.SourceCommitSHA) != nil || len(manifest.Records) != len(candidateTargets) {
		return nil, errors.New("complete canonical candidate identity required for distribution")
	}
	seen := map[string]bool{}
	assets := make([]publicationAsset, 0, 5)
	for _, record := range manifest.Records {
		target, err := targetFor(record.Platform, record.Architecture)
		if err != nil {
			return nil, err
		}
		name, _, _, _, _ := candidateNames(manifest.Version, target)
		if record.Schema != recordSchema || record.Version != manifest.Version || record.SourceCommitSHA != manifest.SourceCommitSHA || record.Archive != name || seen[name] || !hashPattern.MatchString(record.ArtifactSHA256) {
			return nil, errors.New("invalid or duplicate original archive identity")
		}
		seen[name] = true
		file, err := supplyRegularOpen(root, "candidate/"+name, maximumSupplyArchiveSize)
		if err != nil {
			return nil, err
		}
		digest, size, err := publicationHash(file, maximumSupplyArchiveSize)
		if err != nil || size < 1 || digest != record.ArtifactSHA256 {
			return nil, errors.New("original archive hash mismatch")
		}
		assets = append(assets, publicationAsset{name, "candidate/" + name, size, record.ArtifactSHA256})
	}
	sort.Slice(assets, func(i, j int) bool { return assets[i].Name < assets[j].Name })
	sums, err := publicationChecksumBytes(assets)
	if err != nil {
		return nil, err
	}
	assets = append(assets, publicationAsset{publicationChecksumsName, "", int64(len(sums)), supplyDigest(sums)})
	sort.Slice(assets, func(i, j int) bool { return assets[i].Name < assets[j].Name })
	return assets, nil
}

func publicationChecksumBytes(archives []publicationAsset) ([]byte, error) {
	if len(archives) != len(candidateTargets) {
		return nil, errors.New("exactly four archive checksums required")
	}
	var out strings.Builder
	previous := ""
	for _, asset := range archives {
		if !hashPattern.MatchString(asset.SHA256) || asset.Name <= previous || strings.ContainsAny(asset.Name, "/\\:\r\n\t ") || !(strings.HasSuffix(asset.Name, ".zip") || strings.HasSuffix(asset.Name, ".tar.gz")) {
			return nil, errors.New("noncanonical checksum identity or ordering")
		}
		out.WriteString(asset.SHA256 + "  " + asset.Name + "\n")
		previous = asset.Name
	}
	return []byte(out.String()), nil
}

func publicationGeneratedChecksums(assets []publicationAsset) ([]byte, error) {
	var archives []publicationAsset
	for _, asset := range assets {
		if asset.Name != publicationChecksumsName {
			archives = append(archives, asset)
		}
	}
	sort.Slice(archives, func(i, j int) bool { return archives[i].Name < archives[j].Name })
	return publicationChecksumBytes(archives)
}

// Only SHA256SUMS may have no evidence path. Its actual generated bytes must
// match the same size/hash included in the externally approved asset inventory.
func publicationAssetReader(root *os.Root, asset publicationAsset, assets []publicationAsset) (io.ReadCloser, error) {
	if asset.Name == publicationChecksumsName {
		data, err := publicationGeneratedChecksums(assets)
		if err != nil || asset.Path != "" || int64(len(data)) != asset.Size || supplyDigest(data) != asset.SHA256 {
			return nil, errors.New("generated checksum asset binding mismatch")
		}
		return io.NopCloser(bytes.NewReader(data)), nil
	}
	if asset.Path != "candidate/"+asset.Name {
		return nil, errors.New("archive source path mismatch")
	}
	return supplyRegularOpen(root, asset.Path, asset.Size)
}

// A consumer validates every checksum record's canonical shape and identity,
// but only opens its selected archive. Hashes are integrity, not authentication.
func verifySelectedPublication(dir, value, platform, architecture string) error {
	if validateCandidateIdentity(value, strings.Repeat("0", 40)) != nil {
		return errors.New("canonical product version required")
	}
	target, err := targetFor(platform, architecture)
	if err != nil {
		return err
	}
	root, err := supplyOpen(dir)
	if err != nil {
		return err
	}
	defer root.Close()
	data, err := supplyRead(root, publicationChecksumsName)
	if err != nil {
		return err
	}
	names := make([]string, 0, len(candidateTargets))
	for _, candidate := range candidateTargets {
		name, _, _, _, _ := candidateNames(value, candidate)
		names = append(names, name)
	}
	sort.Strings(names)
	lines := strings.Split(string(data), "\n")
	if len(lines) != 5 || lines[4] != "" {
		return errors.New("exactly four LF-terminated checksum records required")
	}
	expected := map[string]string{}
	for i, name := range names {
		line := lines[i]
		if len(line) != 66+len(name) || !hashPattern.MatchString(line[:64]) || line[64:] != "  "+name {
			return errors.New("noncanonical checksum record")
		}
		expected[name] = line[:64]
	}
	name, _, _, _, _ := candidateNames(value, target)
	file, err := supplyRegularOpen(root, name, maximumSupplyArchiveSize)
	if err != nil {
		return err
	}
	digest, _, err := publicationHash(file, maximumSupplyArchiveSize)
	if err != nil || digest != expected[name] {
		return errors.New("selected archive checksum mismatch")
	}
	return nil
}

func runPublicationVerify(arguments []string) error {
	flags := flag.NewFlagSet("publication-verify", flag.ContinueOnError)
	dir := flags.String("dir", "", "directory containing selected archive and SHA256SUMS")
	value := flags.String("version", "", "expected VERSION")
	platform := flags.String("platform", "", "windows or linux")
	architecture := flags.String("architecture", "", "x64 or arm64")
	if err := flags.Parse(arguments); err != nil {
		return err
	}
	if flags.NArg() != 0 || *dir == "" {
		return fmt.Errorf("publication verification requires dir and no positional arguments")
	}
	return verifySelectedPublication(*dir, *value, *platform, *architecture)
}
